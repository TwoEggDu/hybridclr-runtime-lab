using System;
using System.IO;
using HybridCLR;
using HybridCLR.Commands;
using HybridCLR.Installer;
using HybridCLR.Settings;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEditor.SceneManagement;
using UnityEngine;
public static class GcCallbackBuild {
 public static void PrepareAndBuild() {
  var target=BuildTarget.StandaloneWindows64;
        PlayerSettings.SetManagedStrippingLevel(BuildTargetGroup.Standalone, ManagedStrippingLevel.Minimal);
        PlayerSettings.SetIl2CppCodeGeneration(UnityEditor.Build.NamedBuildTarget.Standalone, UnityEditor.Build.Il2CppCodeGeneration.OptimizeSpeed);
  if(!EditorUserBuildSettings.SwitchActiveBuildTarget(BuildTargetGroup.Standalone,target)) throw new Exception("Switch target failed");
  PlayerSettings.SetScriptingBackend(BuildTargetGroup.Standalone,ScriptingImplementation.IL2CPP);
  PlayerSettings.SetIl2CppCompilerConfiguration(BuildTargetGroup.Standalone,Il2CppCompilerConfiguration.Debug);
  EditorUserBuildSettings.development=true;
  EditorUserBuildSettings.allowDebugging=false;
  UnityEditor.WindowsStandalone.UserBuildSettings.createSolution=false;
  PlayerSettings.gcIncremental=true;
  PlayerSettings.productName="GcCallbackProbe";
  PlayerSettings.companyName="TwoEggExperiment";
  var settings=HybridCLRSettings.instance;
  settings.enable=true; settings.useGlobalIl2cpp=false;
  settings.hotUpdateAssemblies=new[]{"HotUpdate"};
  HybridCLRSettings.Save();
  var scene=EditorSceneManager.NewScene(NewSceneSetup.EmptyScene,NewSceneMode.Single);
  EditorSceneManager.SaveScene(scene,"Assets/Probe.unity");
  EditorBuildSettings.scenes=new[]{new EditorBuildSettingsScene("Assets/Probe.unity",true)};
  var root=Path.GetFullPath(Path.Combine(Application.dataPath,"../../.."));
  var plugin=(PluginImporter)AssetImporter.GetAtPath("Assets/Plugins/x86_64/NativeProbe.dll");
  plugin.SetCompatibleWithAnyPlatform(false);plugin.SetCompatibleWithEditor(false);
  plugin.SetCompatibleWithPlatform(BuildTarget.StandaloneWindows64,true);
  plugin.SetPlatformData(BuildTarget.StandaloneWindows64,"CPU","x86_64");plugin.SaveAndReimport();
  Debug.Log("GCP_INSTALL_START "+Application.unityVersion);
  LabRuntime.CheckLock(root);
        if (!new InstallerController().HasInstalledHybridCLR()) new InstallerController().InstallFromLocal(Path.Combine(root,".local/combined-libil2cpp"));
        LabRuntime.SaveLock(root);
  Debug.Log("GCP_GENERATE_START runtime="+SettingsUtil.LocalIl2CppDir);
  PrebuildCommand.GenerateAll();
  Directory.CreateDirectory("Assets/StreamingAssets");
  File.Copy(Path.Combine(SettingsUtil.GetHotUpdateDllsOutputDirByTarget(target),"HotUpdate.dll"),"Assets/StreamingAssets/HotUpdate.dll.bytes",true);
  AssetDatabase.Refresh();
  Debug.Log("GCP_BUILD_START");
  var report=BuildPipeline.BuildPlayer(new BuildPlayerOptions {scenes=new[]{"Assets/Probe.unity"}, locationPathName=Path.Combine(root,"artifacts/incremental-barriers/Player/GcCallbackProbe.exe"),target=target,options=BuildOptions.Development});
  Debug.Log("GCP_BUILD_RESULT "+report.summary.result);
  if(report.summary.result!=BuildResult.Succeeded) throw new Exception("Player build failed");
 }
}
